#!/usr/bin/env python3
"""Generate art/gallery.html — a local, static browser for all game artwork.

Scans the art/ staging lanes and crusade-app/assets/ for images, then
emits a single self-contained HTML file with relative <img> paths.
Re-run it any time new cells land (it is idempotent).

Usage:
    python3 tools/art_gallery.py
    python3 -m http.server 8000   # then open http://localhost:8000/art/gallery.html
"""
from __future__ import annotations

import html
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "art" / "gallery.html"

# section heading -> list of (glob root relative to repo, pattern)
LANES = [
    ("Adversaries (The Road East)", ["art/adversaries-staging"]),
    ("Champions & Fiends (roster)", ["art/roster-staging"]),
    ("Animation staging", ["art/anim-staging"]),
    ("Shipped assets (crusade-app)", ["crusade-app/assets"]),
]
EXTS = {".png", ".gif", ".webp", ".jpg", ".jpeg"}

STYLE = """
body{background:#0B0E1B;color:#E8E3D3;font-family:Georgia,serif;margin:0;padding:2rem}
h1{color:#F4D35E;border-bottom:2px solid #F4D35E;padding-bottom:.4rem}
h2{color:#F4D35E;margin-top:2.5rem}
h3{color:#A62639;margin:1.2rem 0 .4rem}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:14px}
.card{background:#141928;border:1px solid #2a3350;border-radius:6px;padding:8px;text-align:center}
.card img{width:128px;image-rendering:pixelated;border:1px solid #2a3350;background:#0B0E1B}
.card .name{font-size:.8rem;margin-top:.4rem;word-break:break-word}
.card .path{font-size:.6rem;color:#7a8099;word-break:break-all}
a{color:#F4D35E}
.small{color:#7a8099;font-size:.8rem}
"""


def collect(root: Path) -> list[Path]:
    if not root.exists():
        return []
    return sorted(p for p in root.rglob("*") if p.suffix.lower() in EXTS)


def card(rel: Path) -> str:
    name = html.escape(rel.stem)
    group = html.escape(str(rel.parent))
    src = html.escape(str(rel))
    return (
        f'<div class="card"><img loading="lazy" src="../{src}" alt="{name}">'
        f'<div class="name">{name}</div><div class="path">{group}</div></div>'
    )


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    parts = [
        "<!doctype html><html><head><meta charset='utf-8'>"
        "<title>DEUS VULT — Art Gallery</title>",
        f"<style>{STYLE}</style></head><body>",
        "<h1>DEUS VULT — Art Gallery</h1>",
        f"<p class='small'>Generated by tools/art_gallery.py from the local "
        f"tree. Re-run it after new cells land.</p>",
    ]
    total = 0
    for heading, roots in LANES:
        files: list[Path] = []
        for r in roots:
            files += [p.relative_to(ROOT) for p in collect(ROOT / r)]
        if not files:
            parts.append(f"<h2>{html.escape(heading)}</h2><p class='small'>— empty —</p>")
            continue
        parts.append(f"<h2>{html.escape(heading)} ({len(files)})</h2>")
        # group by parent dir (subject)
        groups: dict[str, list[Path]] = {}
        for f in files:
            groups.setdefault(str(f.parent), []).append(f)
        for parent in sorted(groups):
            parts.append(f"<h3>{html.escape(parent)}</h3><div class='grid'>")
            for f in groups[parent]:
                parts.append(card(f))
            parts.append("</div>")
        total += len(files)
    parts.append(f"<p class='small'>{total} images indexed.</p></body></html>")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT} ({total} images)")
    print("serve: python3 -m http.server 8000  ->  http://localhost:8000/art/gallery.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
